@pytest.fixture(scope="module")
def legacy_songs():
    return load_songs("data/songs_v1.csv")


@pytest.mark.parametrize("name", list(V1))
def test_v1_snapshot(name, legacy_songs):
    got = [(s["title"], round(sc, 2)) for s, sc, _ in recommend_songs(PROFILES[name], legacy_songs, 5)]
    assert got == V1[name]


@pytest.mark.parametrize("name", list(EXP))
def test_experiment_snapshot(name, legacy_songs):
    got = [(s["title"], round(sc, 2))
           for s, sc, _ in recommend_songs(PROFILES[name], legacy_songs, 5, EXPERIMENT_WEIGHTS)]
    assert got == EXP[name]


